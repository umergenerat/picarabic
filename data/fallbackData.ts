// دالة للحصول على أسئلة افتراضية
export const getFallbackQuiz = (contextId?: string): QuizQuestion[] => {
    if (contextId) {
        const quiz = fallbackQuizzes.find(q => q.contextId === contextId);
        if (quiz) return quiz.questions;
    }
    // إذا لم نجد، نُرجع أسئلة عشوائية من جميع الاختبارات
    const allQuestions = fallbackQuizzes.flatMap(q => q.questions);
    // اختيار 5 أسئلة عشوائية
    const shuffled = allQuestions.sort(() => 0.5 - Math.random());
    return shuffled.slice(0, 5);
};

