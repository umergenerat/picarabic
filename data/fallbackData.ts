// دالة للحصول على سيناريو افتراضي للمهارة
export const getFallbackScenario = (
    skillId: number,
    specialization: string
): { scenario: string; question: string } | null => {
    const skillData = fallbackSkillScenarios.find(s => s.skillId === skillId);
    if (!skillData) {
        // إذا لم نجد المهارة، نُرجع سيناريو عام
        return {
            scenario: `أنت موظف في مؤسسة مهنية تعمل في مجال ${specialization}. خلال اجتماع الفريق الأسبوعي، لاحظت أن هناك توتراً بين بعض الزملاء حول توزيع المهام. المدير طلب من الجميع التعاون لإنجاز مشروع مهم خلال أسبوع واحد، لكن بعض الأعضاء يشتكون من عبء العمل الزائد بينما آخرون لا يبادرون بالمساعدة.`,
            question: 'كيف ستساهم في تحسين أجواء العمل وتعزيز التعاون بين أعضاء الفريق لإنجاح هذا المشروع؟'
        };
    }

    // البحث عن سيناريو مطابق للتخصص
    let matchedScenario = skillData.scenarios.find(s =>
        specialization.includes(s.specialization) || s.specialization.includes(specialization)
    );

    // إذا لم نجد تطابقاً، نختار سيناريو عشوائي
    if (!matchedScenario) {
        const randomIndex = Math.floor(Math.random() * skillData.scenarios.length);
        matchedScenario = skillData.scenarios[randomIndex];
    }

    return {
        scenario: matchedScenario.scenario,
        question: matchedScenario.question
    };
};

